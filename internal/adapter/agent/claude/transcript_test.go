func writeTranscript(t *testing.T, path string, lines ...string) {
	t.Helper()
	write(t, path, strings.Join(lines, "\n")+"\n")
}

func TestTranscriptLastUserPrompt(t *testing.T) {
	ctx := context.Background()
	dir := t.TempDir()
	stored := filepath.Join(dir, "stored.jsonl")
	writeTranscript(t, stored, transcriptLines...)
	p := Prompts{UserHome: t.TempDir(), Transcript: func(_ context.Context, id string) (string, string, error) {
		if id == "sess-1" {
			return stored, "claude", nil
		}
		return "", "", nil
	}}
	at, ok, err := p.LastUserPrompt(ctx, turn.Session{ID: "term_1", AgentSession: "sess-1", Worktree: "/wt/acme api"})
	if err != nil || !ok || !at.Equal(promptAt) {
		t.Fatalf("LastUserPrompt = %v, %v, %v", at, ok, err)
	}

	home := t.TempDir()
	writeTranscript(t, filepath.Join(home, "projects", projectSlug("/wt/acme api"), "sess-2.jsonl"), transcriptLines[:2]...)
	at, ok, err = p.LastUserPrompt(ctx, turn.Session{ID: "term_2", AgentSession: "sess-2", Worktree: "/wt/acme api", Home: home})
	if err != nil || !ok || !at.Equal(time.Date(2026, 10, 21, 12, 0, 0, 0, time.UTC)) {
		t.Fatalf("from the worktree's project: %v, %v, %v", at, ok, err)
	}
}

