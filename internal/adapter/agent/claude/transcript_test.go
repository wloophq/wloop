func TestAnUnchangedTranscriptIsReadOnce(t *testing.T) {
	ctx := context.Background()
	path := filepath.Join(t.TempDir(), "stored.jsonl")
	first := `{"type":"user","timestamp":"2026-10-21T12:00:00Z","message":{"role":"user","content":"one"}}`
	writeTranscript(t, path, first)
	p := Prompts{UserHome: t.TempDir(), Transcript: func(context.Context, string) (string, string, error) { return path, "claude", nil }}
	sess := turn.Session{ID: "term_1", AgentSession: "sess-1"}
	at, _, err := p.LastUserPrompt(ctx, sess)
	if err != nil || !at.Equal(time.Date(2026, 10, 21, 12, 0, 0, 0, time.UTC)) {
		t.Fatalf("first read = %v, %v", at, err)
	}
	info, err := os.Stat(path)
	if err != nil {
		t.Fatal(err)
	}
	writeTranscript(t, path, strings.Replace(first, "12:00:00", "12:00:09", 1))
	if err := os.Chtimes(path, info.ModTime(), info.ModTime()); err != nil {
		t.Fatal(err)
	}
	if at, _, _ := p.LastUserPrompt(ctx, sess); !at.Equal(time.Date(2026, 10, 21, 12, 0, 0, 0, time.UTC)) {
		t.Errorf("a transcript of the same size and time was read again: %v", at)
	}
	if err := os.Chtimes(path, info.ModTime().Add(time.Second), info.ModTime().Add(time.Second)); err != nil {
		t.Fatal(err)
	}
	if at, _, _ := p.LastUserPrompt(ctx, sess); !at.Equal(time.Date(2026, 10, 21, 12, 0, 9, 0, time.UTC)) {
		t.Errorf("a moved transcript was not read again: %v", at)
	}
}
