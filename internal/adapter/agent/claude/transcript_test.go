func TestPromptsContract(t *testing.T) {
	turnstest.RunPrompts(t, func(t *testing.T) (turns.Prompts, turnstest.PromptsWorld) {
		home := t.TempDir()
		project := filepath.Join(home, "projects", projectSlug("/wt/api"))
		writeTranscript(t, filepath.Join(project, "sess-1.jsonl"), transcriptLines...)
		writeTranscript(t, filepath.Join(project, "sess-2.jsonl"), transcriptLines[1])
		s := func(h, id string) turn.Session {
			return turn.Session{ID: h, AgentSession: id, Worktree: "/wt/api", Home: home}
		}
		return Prompts{UserHome: t.TempDir()}, turnstest.PromptsWorld{Prompted: s("term_1", "sess-1"), Quiet: s("term_2", "sess-2"), Unknown: s("term_3", "sess-3"), At: promptAt}
	})
}

